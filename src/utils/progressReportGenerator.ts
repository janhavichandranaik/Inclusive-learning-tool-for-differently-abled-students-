import { LESSONS, SUBJECTS } from '../data/curriculum';
import { getLocalizedLesson, getLocalizedSubject } from '../data/multilingualMaterials';
import { AccessibilityProfileMode, AppLanguage, ProgressState, StudentProfile } from '../types';

export interface ReportContext {
  student: StudentProfile | null;
  language: AppLanguage;
  profileMode?: AccessibilityProfileMode;
  progress: ProgressState;
  completedCount: number;
  totalLessons: number;
  quizzesCompletedCount: number;
  averageQuizScore: number;
  overallPercent: number;
}

interface ReportLessonRow {
  title: string;
  numberLabel: string;
  completed: boolean;
  bestQuizScore?: number;
  quizAttempts: number;
}

interface ReportSubjectBlock {
  title: string;
  done: number;
  total: number;
  pct: number;
  lessons: ReportLessonRow[];
}

function formatModeLabel(mode?: AccessibilityProfileMode): string {
  if (mode === 'visual') return 'Visual Support (Audio & TTS)';
  if (mode === 'hearing') return 'Hearing Support (Subtitles & Sign)';
  return 'Balanced Multi-Sensory';
}

function formatLanguageLabel(lang: AppLanguage): string {
  if (lang === 'kn') return 'ಕನ್ನಡ (Kannada)';
  if (lang === 'hi') return 'हिन्दी (Hindi)';
  return 'English';
}

function buildSubjectBlocks(progress: ProgressState, language: AppLanguage): ReportSubjectBlock[] {
  return SUBJECTS.map((rawSubject) => {
    const subject = getLocalizedSubject(rawSubject, language);
    const subjectLessons = LESSONS.filter((l) => l.subjectId === subject.id);
    const rows: ReportLessonRow[] = subjectLessons.map((rawLesson) => {
      const lesson = getLocalizedLesson(rawLesson, language);
      const rec = progress.lessons[lesson.id];
      return {
        title: lesson.title,
        numberLabel: lesson.numberLabel,
        completed: Boolean(rec?.completed),
        bestQuizScore: rec?.bestQuizScore,
        quizAttempts: rec?.quizAttempts ?? 0,
      };
    });
    const done = rows.filter((r) => r.completed).length;
    const pct = rows.length > 0 ? Math.round((done / rows.length) * 100) : 0;
    return {
      title: subject.title,
      done,
      total: rows.length,
      pct,
      lessons: rows,
    };
  });
}

export function buildTextProgressSummary(ctx: ReportContext): string {
  const blocks = buildSubjectBlocks(ctx.progress, ctx.language);
  const generatedAt = new Date().toLocaleString();
  const studentName = ctx.student?.name ?? 'Guest Student';
  const studentId = ctx.student?.studentId ?? 'Not signed in';
  const grade = ctx.student?.gradeLevel ?? 'General';
  const modeLabel = formatModeLabel(ctx.student?.preferredMode ?? ctx.profileMode);

  const lines: string[] = [
    '============================================================',
    'CLARITYLEARN — STUDENT PROGRESS & QUIZ SUMMARY REPORT',
    'For Teachers, Parents & Caregivers',
    '============================================================',
    `Generated: ${generatedAt}`,
    `Student Name: ${studentName}`,
    `Student ID: ${studentId}`,
    `Grade / Level: ${grade}`,
    `Preferred Learning Mode: ${modeLabel}`,
    `Report Language: ${formatLanguageLabel(ctx.language)}`,
    '',
    'OVERALL SUMMARY',
    '------------------------------------------------------------',
    `Overall Mastery: ${ctx.overallPercent}% (${ctx.completedCount} of ${ctx.totalLessons} lessons completed)`,
    `Average Quiz Score: ${ctx.quizzesCompletedCount > 0 ? `${ctx.averageQuizScore}%` : 'No quizzes completed yet'} (${ctx.quizzesCompletedCount} quizzes completed)`,
    `Study Time Logged: ${ctx.progress.totalMinutesSpent} minutes`,
    '',
    'SUBJECT & QUIZ BREAKDOWN',
    '------------------------------------------------------------',
  ];

  for (const block of blocks) {
    lines.push(`${block.title} — ${block.done}/${block.total} lessons (${block.pct}%)`);
    for (const row of block.lessons) {
      const status = row.completed ? 'Completed' : 'In Progress / Not Started';
      const quizText =
        typeof row.bestQuizScore === 'number'
          ? `Best Quiz: ${row.bestQuizScore}% (${row.quizAttempts} attempt${row.quizAttempts === 1 ? '' : 's'})`
          : 'Quiz: Not attempted';
      lines.push(`  • ${row.numberLabel}: ${row.title}`);
      lines.push(`    Status: ${status} | ${quizText}`);
    }
    lines.push('');
  }

  if (ctx.progress.activityLog.length > 0) {
    lines.push('RECENT STUDY MILESTONES');
    lines.push('------------------------------------------------------------');
    for (const entry of ctx.progress.activityLog.slice(0, 8)) {
      lines.push(`  • [${entry.timestamp}] ${entry.label} — ${entry.detail}`);
    }
    lines.push('');
  }

  lines.push('Generated by ClarityLearn Inclusive Learning Content Tool');
  return lines.join('\n');
}

export function downloadTextProgressReport(ctx: ReportContext): void {
  const content = buildTextProgressSummary(ctx);
  const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `claritylearn-progress-summary-${new Date().toISOString().slice(0, 10)}.txt`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

// Wrap text into lines fitting maxWidth on a Canvas 2D context
function wrapCanvasText(
  context: CanvasRenderingContext2D,
  text: string,
  maxWidth: number
): string[] {
  const words = text.split(/\s+/).filter(Boolean);
  if (words.length === 0) return [''];
  const lines: string[] = [];
  let current = words[0];

  for (let i = 1; i < words.length; i++) {
    const candidate = `${current} ${words[i]}`;
    if (context.measureText(candidate).width <= maxWidth) {
      current = candidate;
    } else {
      lines.push(current);
      current = words[i];
    }
  }
  lines.push(current);
  return lines;
}

function drawRoundedRect(
  c: CanvasRenderingContext2D,
  x: number,
  y: number,
  w: number,
  h: number,
  r: number
): void {
  c.beginPath();
  c.moveTo(x + r, y);
  c.lineTo(x + w - r, y);
  c.quadraticCurveTo(x + w, y, x + w, y + r);
  c.lineTo(x + w, y + h - r);
  c.quadraticCurveTo(x + w, y + h, x + w - r, y + h);
  c.lineTo(x + r, y + h);
  c.quadraticCurveTo(x, y + h, x, y + h - r);
  c.lineTo(x, y + r);
  c.quadraticCurveTo(x, y, x + r, y);
  c.closePath();
}

function dataUrlToUint8Array(dataUrl: string): Uint8Array {
  const base64 = dataUrl.split(',')[1] ?? '';
  const binary = atob(base64);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) {
    bytes[i] = binary.charCodeAt(i);
  }
  return bytes;
}

// Assemble a valid multi-page PDF 1.4 document from JPEG canvas images
function buildPdfFromJpegPages(
  pages: { jpegBytes: Uint8Array; width: number; height: number }[]
): Uint8Array {
  const encoder = new TextEncoder();
  const chunks: Uint8Array[] = [];
  let offset = 0;

  const pushStr = (s: string) => {
    const b = encoder.encode(s);
    chunks.push(b);
    offset += b.length;
  };

  const pushBytes = (b: Uint8Array) => {
    chunks.push(b);
    offset += b.length;
  };

  // Header with binary comment marker
  pushStr('%PDF-1.4\n%\xE2\xE3\xCF\xD3\n');

  const objectOffsets: number[] = [0]; // 1-indexed objects; index 0 is free entry
  const totalPages = pages.length;
  // Object layout:
  // 1 = Catalog
  // 2 = Pages
  // For each page i (0..totalPages-1):
  //   3 + i*3     = Image XObject
  //   3 + i*3 + 1 = Page Content Stream
  //   3 + i*3 + 2 = Page Object
  const pageObjIds: number[] = [];
  for (let i = 0; i < totalPages; i++) {
    pageObjIds.push(3 + i * 3 + 2);
  }

  // Obj 1: Catalog
  objectOffsets[1] = offset;
  pushStr('1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n');

  // Obj 2: Pages
  objectOffsets[2] = offset;
  pushStr(
    `2 0 obj\n<< /Type /Pages /Kids [${pageObjIds.map((id) => `${id} 0 R`).join(' ')}] /Count ${totalPages} >>\nendobj\n`
  );

  // A4 dimensions in PDF points (72 dpi)
  const ptWidth = 595.28;
  const ptHeight = 841.89;

  pages.forEach((page, i) => {
    const imgId = 3 + i * 3;
    const contentId = imgId + 1;
    const pageId = imgId + 2;

    // Image XObject
    objectOffsets[imgId] = offset;
    pushStr(
      `${imgId} 0 obj\n<< /Type /XObject /Subtype /Image /Width ${page.width} /Height ${page.height} /ColorSpace /DeviceRGB /BitsPerComponent 8 /Filter /DCTDecode /Length ${page.jpegBytes.length} >>\nstream\n`
    );
    pushBytes(page.jpegBytes);
    pushStr('\nendstream\nendobj\n');

    // Content stream drawing image full-bleed onto A4 page
    const streamCmd = `q ${ptWidth.toFixed(2)} 0 0 ${ptHeight.toFixed(2)} 0 0 cm /Im${i} Do Q\n`;
    const streamBytes = encoder.encode(streamCmd);
    objectOffsets[contentId] = offset;
    pushStr(`${contentId} 0 obj\n<< /Length ${streamBytes.length} >>\nstream\n`);
    pushBytes(streamBytes);
    pushStr('endstream\nendobj\n');

    // Page Object
    objectOffsets[pageId] = offset;
    pushStr(
      `${pageId} 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${ptWidth.toFixed(2)} ${ptHeight.toFixed(2)}] /Resources << /XObject << /Im${i} ${imgId} 0 R >> >> /Contents ${contentId} 0 R >>\nendobj\n`
    );
  });

  const xrefOffset = offset;
  const totalObjects = objectOffsets.length;
  pushStr(`xref\n0 ${totalObjects}\n`);
  pushStr('0000000000 65535 f \n');
  for (let id = 1; id < totalObjects; id++) {
    const offStr = String(objectOffsets[id]).padStart(10, '0');
    pushStr(`${offStr} 00000 n \n`);
  }

  pushStr(
    `trailer\n<< /Size ${totalObjects} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF`
  );

  const combined = new Uint8Array(offset);
  let pos = 0;
  for (const chunk of chunks) {
    combined.set(chunk, pos);
    pos += chunk.length;
  }
  return combined;
}

export function downloadPdfProgressReport(ctx: ReportContext): void {
  const PAGE_W = 1240; // A4 @ 150dpi
  const PAGE_H = 1754;
  const MARGIN = 72;
  const CONTENT_W = PAGE_W - MARGIN * 2;
  const BOTTOM_LIMIT = PAGE_H - 96;
  const FONT_FAMILY =
    '"Plus Jakarta Sans", "Noto Sans Kannada", "Noto Sans Devanagari", system-ui, -apple-system, sans-serif';

  const renderedPages: HTMLCanvasElement[] = [];

  const createNewPage = (pageNum: number): { canvas: HTMLCanvasElement; c: CanvasRenderingContext2D; y: number } => {
    const canvas = document.createElement('canvas');
    canvas.width = PAGE_W;
    canvas.height = PAGE_H;
    const c = canvas.getContext('2d')!;

    // Crisp white paper background
    c.fillStyle = '#FFFFFF';
    c.fillRect(0, 0, PAGE_W, PAGE_H);

    // Top accent bar
    c.fillStyle = '#0B4F8A';
    c.fillRect(0, 0, PAGE_W, 14);

    if (pageNum > 1) {
      c.fillStyle = '#475569';
      c.font = `600 18px ${FONT_FAMILY}`;
      c.fillText(`ClarityLearn Student Progress & Quiz Report — Page ${pageNum}`, MARGIN, 56);
      c.strokeStyle = '#E2E8F0';
      c.lineWidth = 2;
      c.beginPath();
      c.moveTo(MARGIN, 74);
      c.lineTo(PAGE_W - MARGIN, 74);
      c.stroke();
      return { canvas, c, y: 108 };
    }

    return { canvas, c, y: 58 };
  };

  let pageIndex = 1;
  let page = createNewPage(pageIndex);
  renderedPages.push(page.canvas);

  const ensureSpace = (neededHeight: number) => {
    if (page.y + neededHeight > BOTTOM_LIMIT) {
      pageIndex += 1;
      page = createNewPage(pageIndex);
      renderedPages.push(page.canvas);
    }
  };

  const c = () => page.c;

  // --- PAGE 1 HEADER ---
  c().fillStyle = '#0F172A';
  c().font = `800 36px ${FONT_FAMILY}`;
  c().fillText('ClarityLearn', MARGIN, page.y + 18);

  c().fillStyle = '#0B4F8A';
  c().font = `700 20px ${FONT_FAMILY}`;
  c().fillText('Student Learning Progress & Quiz Summary', MARGIN, page.y + 52);

  const dateText = `Generated: ${new Date().toLocaleDateString()} · ${new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })}`;
  c().fillStyle = '#475569';
  c().font = `600 17px ${FONT_FAMILY}`;
  const dateWidth = c().measureText(dateText).width;
  c().fillText(dateText, PAGE_W - MARGIN - dateWidth, page.y + 20);

  page.y += 78;

  // Student Info Card
  drawRoundedRect(c(), MARGIN, page.y, CONTENT_W, 114, 12);
  c().fillStyle = '#F8FAFC';
  c().fill();
  c().strokeStyle = '#CBD5E1';
  c().lineWidth = 2;
  c().stroke();

  const studentName = ctx.student?.name ?? 'Guest Student';
  const studentId = ctx.student?.studentId ?? 'Local Session';
  const grade = ctx.student?.gradeLevel ?? 'Inclusive Curriculum';
  const modeStr = formatModeLabel(ctx.student?.preferredMode ?? ctx.profileMode);
  const langStr = formatLanguageLabel(ctx.language);

  c().fillStyle = '#0F172A';
  c().font = `700 22px ${FONT_FAMILY}`;
  c().fillText(`Student: ${studentName}`, MARGIN + 24, page.y + 38);

  c().fillStyle = '#334155';
  c().font = `600 18px ${FONT_FAMILY}`;
  c().fillText(`ID: ${studentId}   ·   Grade: ${grade}`, MARGIN + 24, page.y + 68);
  c().fillText(`Mode: ${modeStr}   ·   Language: ${langStr}`, MARGIN + 24, page.y + 96);

  page.y += 140;

  // 4-Column KPI Summary Row
  const kpiGap = 18;
  const kpiW = (CONTENT_W - kpiGap * 3) / 4;
  const kpis = [
    { label: 'Overall Mastery', value: `${ctx.overallPercent}%`, sub: `${ctx.completedCount}/${ctx.totalLessons} lessons` },
    { label: 'Lessons Done', value: `${ctx.completedCount}`, sub: `Across ${SUBJECTS.length} subjects` },
    {
      label: 'Avg Quiz Score',
      value: ctx.quizzesCompletedCount > 0 ? `${ctx.averageQuizScore}%` : '—',
      sub: `${ctx.quizzesCompletedCount} quizzes taken`,
    },
    { label: 'Study Time', value: `${ctx.progress.totalMinutesSpent} min`, sub: 'Logged study time' },
  ];

  kpis.forEach((kpi, idx) => {
    const kx = MARGIN + idx * (kpiW + kpiGap);
    drawRoundedRect(c(), kx, page.y, kpiW, 116, 12);
    c().fillStyle = '#FFFFFF';
    c().fill();
    c().strokeStyle = '#CBD5E1';
    c().lineWidth = 2;
    c().stroke();

    c().fillStyle = '#475569';
    c().font = `700 16px ${FONT_FAMILY}`;
    c().fillText(kpi.label, kx + 18, page.y + 32);

    c().fillStyle = '#0B4F8A';
    c().font = `800 34px ${FONT_FAMILY}`;
    c().fillText(kpi.value, kx + 18, page.y + 74);

    c().fillStyle = '#64748B';
    c().font = `500 15px ${FONT_FAMILY}`;
    c().fillText(kpi.sub, kx + 18, page.y + 100);
  });

  page.y += 148;

  // Section Heading: Subject & Quiz Breakdown
  c().fillStyle = '#0F172A';
  c().font = `800 24px ${FONT_FAMILY}`;
  c().fillText('Subject & Quiz Score Breakdown', MARGIN, page.y);
  page.y += 22;

  const blocks = buildSubjectBlocks(ctx.progress, ctx.language);

  for (const block of blocks) {
    const estimatedHeight = 86 + block.lessons.length * 56;
    ensureSpace(Math.min(estimatedHeight, 260));

    // Subject Header Strip
    drawRoundedRect(c(), MARGIN, page.y, CONTENT_W, 66, 10);
    c().fillStyle = '#EFF6FF';
    c().fill();
    c().strokeStyle = '#BFDBFE';
    c().lineWidth = 1.5;
    c().stroke();

    c().fillStyle = '#0F172A';
    c().font = `700 20px ${FONT_FAMILY}`;
    const subjectTitleLines = wrapCanvasText(c(), block.title, CONTENT_W - 260);
    c().fillText(subjectTitleLines[0], MARGIN + 20, page.y + 32);

    c().fillStyle = '#0B4F8A';
    c().font = `700 18px ${FONT_FAMILY}`;
    const statStr = `${block.done}/${block.total} Completed · ${block.pct}%`;
    const statW = c().measureText(statStr).width;
    c().fillText(statStr, PAGE_W - MARGIN - 20 - statW, page.y + 32);

    // Subject progress bar
    const barX = MARGIN + 20;
    const barY = page.y + 44;
    const barW = CONTENT_W - 40;
    drawRoundedRect(c(), barX, barY, barW, 10, 5);
    c().fillStyle = '#DBEAFE';
    c().fill();
    if (block.pct > 0) {
      drawRoundedRect(c(), barX, barY, Math.max(12, (barW * block.pct) / 100), 10, 5);
      c().fillStyle = '#0B4F8A';
      c().fill();
    }

    page.y += 76;

    // Lesson Rows
    for (const row of block.lessons) {
      ensureSpace(64);
      drawRoundedRect(c(), MARGIN + 10, page.y, CONTENT_W - 20, 50, 8);
      c().fillStyle = row.completed ? '#F0FDF4' : '#F8FAFC';
      c().fill();
      c().strokeStyle = row.completed ? '#BBF7D0' : '#E2E8F0';
      c().lineWidth = 1.5;
      c().stroke();

      c().fillStyle = '#0F172A';
      c().font = `600 17px ${FONT_FAMILY}`;
      const labelText = `${row.numberLabel} · ${row.title}`;
      const trimmed =
        c().measureText(labelText).width > CONTENT_W - 380
          ? `${wrapCanvasText(c(), labelText, CONTENT_W - 400)[0]}…`
          : labelText;
      c().fillText(trimmed, MARGIN + 26, page.y + 31);

      const statusText = row.completed ? 'Completed' : 'In Progress';
      const quizText =
        typeof row.bestQuizScore === 'number'
          ? `Quiz: ${row.bestQuizScore}%`
          : 'Quiz: —';
      const rightSummary = `${statusText}   ·   ${quizText}`;

      c().fillStyle = row.completed ? '#166534' : '#475569';
      c().font = `700 16px ${FONT_FAMILY}`;
      const rightW = c().measureText(rightSummary).width;
      c().fillText(rightSummary, PAGE_W - MARGIN - 28 - rightW, page.y + 31);

      page.y += 58;
    }

    page.y += 14;
  }

  // Recent Activity Section (if any)
  if (ctx.progress.activityLog.length > 0) {
    ensureSpace(140);
    page.y += 8;
    c().fillStyle = '#0F172A';
    c().font = `800 22px ${FONT_FAMILY}`;
    c().fillText('Recent Study Milestones', MARGIN, page.y);
    page.y += 22;

    for (const entry of ctx.progress.activityLog.slice(0, 6)) {
      ensureSpace(58);
      drawRoundedRect(c(), MARGIN, page.y, CONTENT_W, 46, 8);
      c().fillStyle = '#F8FAFC';
      c().fill();
      c().strokeStyle = '#E2E8F0';
      c().lineWidth = 1.5;
      c().stroke();

      c().fillStyle = '#0F172A';
      c().font = `700 16px ${FONT_FAMILY}`;
      c().fillText(`${entry.label} — ${entry.detail}`, MARGIN + 18, page.y + 29);

      c().fillStyle = '#64748B';
      c().font = `500 15px ${FONT_FAMILY}`;
      const tsW = c().measureText(entry.timestamp).width;
      c().fillText(entry.timestamp, PAGE_W - MARGIN - 18 - tsW, page.y + 29);

      page.y += 54;
    }
  }

  // Footers across all pages
  renderedPages.forEach((pCanvas, idx) => {
    const pc = pCanvas.getContext('2d')!;
    pc.strokeStyle = '#E2E8F0';
    pc.lineWidth = 1.5;
    pc.beginPath();
    pc.moveTo(MARGIN, PAGE_H - 64);
    pc.lineTo(PAGE_W - MARGIN, PAGE_H - 64);
    pc.stroke();

    pc.fillStyle = '#64748B';
    pc.font = `500 15px ${FONT_FAMILY}`;
    pc.fillText(
      'ClarityLearn · Inclusive Learning Progress Report for Teachers & Parents',
      MARGIN,
      PAGE_H - 36
    );
    const pgLabel = `Page ${idx + 1} of ${renderedPages.length}`;
    const pgW = pc.measureText(pgLabel).width;
    pc.fillText(pgLabel, PAGE_W - MARGIN - pgW, PAGE_H - 36);
  });

  const jpegPages = renderedPages.map((pCanvas) => ({
    jpegBytes: dataUrlToUint8Array(pCanvas.toDataURL('image/jpeg', 0.92)),
    width: pCanvas.width,
    height: pCanvas.height,
  }));

  const pdfBytes = buildPdfFromJpegPages(jpegPages);
  const blob = new Blob([pdfBytes.buffer as ArrayBuffer], { type: 'application/pdf' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `claritylearn-progress-report-${new Date().toISOString().slice(0, 10)}.pdf`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
