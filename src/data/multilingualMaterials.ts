export function hasBuiltInLessonTranslation(lessonId: string, language: AppLanguage): boolean {
  if (language === 'en') return true;
  return Boolean(LESSON_TRANSLATIONS[language]?.[lessonId]);
}

export function getLocalizedSubject(subject: Subject, language: AppLanguage): Subject {
  if (language === 'en') return subject;
  const tr = SUBJECT_TRANSLATIONS[language]?.[subject.id];
  if (!tr) return subject;
  return {
    ...subject,
    title: tr.title,
    subtitle: tr.subtitle,
    description: tr.description,
  };
}

export function getLocalizedLesson(lesson: Lesson, language: AppLanguage): Lesson {
  if (language === 'en') return lesson;
  const tr = LESSON_TRANSLATIONS[language]?.[lesson.id];
  if (!tr) return lesson;

  return {
    ...lesson,
    title: tr.title,
    subtitle: tr.subtitle,
    objectives: tr.objectives,
    cues: lesson.cues.map((c) => ({
      ...c,
      caption: tr.cues[c.id] ?? c.caption,
    })),
    readingSections: lesson.readingSections.map((sec, idx) => ({
      ...sec,
      heading: tr.readingSections[idx]?.heading ?? sec.heading,
      body: tr.readingSections[idx]?.body ?? sec.body,
      keyTakeaway: tr.readingSections[idx]?.keyTakeaway ?? sec.keyTakeaway,
    })),
    quiz: lesson.quiz.map((q, idx) => ({
      ...q,
      prompt: tr.quiz[idx]?.prompt ?? q.prompt,
      options: tr.quiz[idx]?.options ?? q.options,
      hint: tr.quiz[idx]?.hint ?? q.hint,
      explanation: tr.quiz[idx]?.explanation ?? q.explanation,
    })),
  };
}
